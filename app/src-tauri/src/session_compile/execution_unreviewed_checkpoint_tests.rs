#[test]
fn intervening_durable_checkpoint_is_not_replaced_by_a_late_unreviewed_draft() {
    with_isolated_data("compiler-unreviewed-checkpoint-cas", |_| {
        let (dir, vault, origin, source) = request_fixture();
        let plan =
            session::sources::prepare(&source, REQUEST, &origin, "en", |_, _| Ok(800)).unwrap();
        let context = session::begin(&vault, &origin, source, RoleUsage::Foreground).unwrap();
        let human_path = human_file(dir.path(), &context);
        let original = std::fs::read(dir.path().join(&context.source.raw_path)).unwrap();
        let mut intervening_queue = None;
        let mut intervening_progress = None;
        let error = step(
            &vault,
            &context,
            "en",
            &AtomicBool::new(false),
            |_, _| Ok(800),
            |_, user, _, _, stage| {
                if stage != CompilerSchema::Review {
                    return Ok(raw_reply(stage, user));
                }
                let mut pending = Pending::try_load(dir.path()).unwrap();
                let attempt = &mut pending.compile_jobs[0].attempts[0];
                attempt.compiler_progress = Some(
                    CompilerRun::new(&context.attempt_id, &context.compile_signature)
                        .initial_progress(&plan),
                );
                intervening_progress =
                    Some(serde_json::to_value(&attempt.compiler_progress).unwrap());
                pending.save(dir.path()).unwrap();
                intervening_queue = Some(std::fs::read(Pending::path(dir.path())).unwrap());
                Err(REVIEW_UNAVAILABLE.into())
            },
        )
        .err()
        .unwrap();
        assert!(error.message.contains(REVIEW_UNAVAILABLE));
        assert!(error.outcome.is_none());
        assert!(error
            .finalization_error
            .as_ref()
            .unwrap()
            .contains("checkpoint changed"));
        let pending = Pending::try_load(dir.path()).unwrap();
        assert_eq!(
            serde_json::to_value(&pending.compile_jobs[0].attempts[0].compiler_progress).unwrap(),
            intervening_progress.unwrap()
        );
        assert_eq!(
            std::fs::read(Pending::path(dir.path())).unwrap(),
            intervening_queue.unwrap()
        );
        assert!(pending.compile_jobs[0].attempts[0].outputs.is_empty());
        assert!(pending.compile_jobs[0].receipts.is_empty());
        assert!(pending.receipts.is_empty());
        assert_eq!(
            std::fs::read(dir.path().join(&context.source.raw_path)).unwrap(),
            original
        );
        assert_eq!(std::fs::read(&human_path).unwrap(), HUMAN);
        assert!(authorize(&vault, &context).is_err());
    });
}

#[cfg(unix)]
#[test]
fn denied_unreviewed_checkpoint_save_preserves_disk_bytes_and_retires_unconfirmed_owner() {
    use std::os::unix::fs::PermissionsExt;
    struct RestorePermissions {
        directory: std::path::PathBuf,
        permissions: std::fs::Permissions,
    }
    impl Drop for RestorePermissions {
        fn drop(&mut self) {
            if let Err(error) = std::fs::set_permissions(&self.directory, self.permissions.clone())
            {
                if std::thread::panicking() {
                    eprintln!("restore synthetic unreviewed queue permissions: {error}");
                } else {
                    panic!("restore synthetic unreviewed queue permissions: {error}");
                }
            }
        }
    }
    with_isolated_data("compiler-unreviewed-denied-save", |_| {
        let (dir, vault, origin, source) = request_fixture();
        let context = session::begin(&vault, &origin, source, RoleUsage::Foreground).unwrap();
        let human_path = human_file(dir.path(), &context);
        let original = std::fs::read(dir.path().join(&context.source.raw_path)).unwrap();
        let queue_path = Pending::path(dir.path());
        let queue_before = std::fs::read(&queue_path).unwrap();
        let queue_parent = queue_path.parent().unwrap().to_path_buf();
        let permissions = std::fs::metadata(&queue_parent).unwrap().permissions();
        let mode = permissions.mode();
        let mut restore = None;
        let mut calls = Vec::new();
        let error = step(
            &vault,
            &context,
            "en",
            &AtomicBool::new(false),
            |_, _| Ok(800),
            |_, user, _, _, stage| {
                calls.push(stage);
                if stage != CompilerSchema::Review {
                    return Ok(raw_reply(stage, user));
                }
                restore = Some(RestorePermissions {
                    directory: queue_parent.clone(),
                    permissions: permissions.clone(),
                });
                std::fs::set_permissions(
                    &queue_parent,
                    std::fs::Permissions::from_mode(mode & !0o222),
                )
                .unwrap();
                let probe = std::fs::OpenOptions::new()
                    .write(true)
                    .create_new(true)
                    .open(queue_parent.join("synthetic-unreviewed-denied-write-probe"));
                assert!(
                    matches!(&probe,
                    Err(error) if error.kind() == std::io::ErrorKind::PermissionDenied),
                    "actual filesystem write denial is required: {probe:?}"
                );
                Err(REVIEW_UNAVAILABLE.into())
            },
        )
        .err()
        .unwrap();
        assert_eq!(
            calls,
            vec![
                CompilerSchema::Claims,
                CompilerSchema::Compilation,
                CompilerSchema::Review
            ]
        );
        assert!(error.message.contains(REVIEW_UNAVAILABLE));
        assert!(error.outcome.is_none());
        let finalization = error.finalization_error.as_ref().unwrap();
        assert!(finalization.contains("publish wikify queue"));
        assert!(finalization.contains("tempfile create failed"));
        assert_eq!(std::fs::read(&queue_path).unwrap(), queue_before);
        let pending = Pending::try_load(dir.path()).unwrap();
        assert!(pending.compile_jobs[0].attempts[0]
            .compiler_progress
            .is_none());
        assert!(pending.compile_jobs[0].attempts[0].outputs.is_empty());
        assert!(pending.compile_jobs[0].attempts[0]
            .prepared_outputs
            .is_empty());
        assert!(pending.compile_jobs[0].receipts.is_empty());
        assert!(pending.receipts.is_empty());
        assert_eq!(
            std::fs::read(dir.path().join(&context.source.raw_path)).unwrap(),
            original
        );
        assert_eq!(std::fs::read(&human_path).unwrap(), HUMAN);
        drop(restore.take());
        assert_eq!(
            std::fs::metadata(&queue_parent)
                .unwrap()
                .permissions()
                .mode(),
            mode
        );
        assert!(authorize(&vault, &context).is_err());
        let retry = session::begin(
            &vault,
            &origin,
            context.source.clone(),
            RoleUsage::Foreground,
        )
        .unwrap();
        assert_ne!(retry.attempt_id, context.attempt_id);
        let after = Pending::try_load(dir.path()).unwrap();
        assert!(after.compile_jobs[0]
            .attempts
            .last()
            .unwrap()
            .compiler_progress
            .is_none());
        assert!(after.compile_jobs[0].receipts.is_empty());
    });
}
