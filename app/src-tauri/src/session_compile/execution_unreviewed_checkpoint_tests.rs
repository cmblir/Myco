//! Native RED for durable unreviewed checkpoint preservation.
//! Generation and token counts are synthetic plumbing fixtures, not model
//! meaning, actual tokenizer measurements or installed acceptance.

use super::*;
use crate::session_compile as session;

const REQUEST: &str = "---\nsource: codex\nconversation_id: synthetic-native\ncreated: 2026-10-01\n---\n**User:**\nPlease request the synthetic report.\n";
const HUMAN: &[u8] = b"# Synthetic human title\nHuman annotation remains.\n";
const REVIEW_UNAVAILABLE: &str = "synthetic unreviewed transport unavailable";

fn request_fixture() -> (
    tempfile::TempDir,
    VaultRoot,
    AgentVaultSession,
    session::SourceBinding,
) {
    let dir = tempfile::Builder::new()
        .prefix("myco-compiler-unreviewed-synthetic-")
        .tempdir()
        .unwrap();
    // A separate one-window fixture reaches nonempty structure generation at
    // packet zero. It does not edit or replace the retained whole-source gold.
    let raw_path = "raw/conversations/codex/synthetic-native.md".to_string();
    crate::importers::wikify::append_raw(dir.path(), &raw_path, REQUEST).unwrap();
    let source = session::SourceBinding {
        key: "codex:synthetic-native".into(),
        raw_path,
        source_revision: source_revision(REQUEST),
    };
    let mut pending = Pending::default();
    pending.push(PendingItem {
        key: source.key.clone(),
        raw_path: source.raw_path.clone(),
        source_revision: source.source_revision.clone(),
        src_slug: "src-synthetic-native".into(),
        title: "Synthetic request".into(),
        imported: "2026-10-09".into(),
        read_ranges: vec![],
    });
    pending.save(dir.path()).unwrap();
    let vault = VaultRoot::default();
    reopen(&vault, dir.path());
    let origin = vault.snapshot().unwrap();
    (dir, vault, origin, source)
}

fn human_file(root: &std::path::Path, context: &SessionCompileContext) -> std::path::PathBuf {
    let path = root.join(&context.summary_path);
    std::fs::create_dir_all(path.parent().unwrap()).unwrap();
    std::fs::write(&path, HUMAN).unwrap();
    path
}

fn raw_reply(stage: CompilerSchema, user: &str) -> String {
    let output = session::compiler::fixture_model(stage, user, false).unwrap();
    // Raw checkpoint fidelity includes harmless whitespace, rather than a
    // parse-and-reserialize approximation of the generated bytes.
    format!(" \n{output}\n ")
}

#[derive(Clone, Copy)]
enum ReviewFailure {
    Transport,
    InputBudget,
    Tokenizer,
}

#[test]
fn review_transport_error_retains_exact_unreviewed_native_checkpoint_without_publication() {
    assert_unreviewed_checkpoint(ReviewFailure::Transport);
}

#[test]
fn review_input_3321_retains_exact_unreviewed_native_checkpoint_without_advancing_cursor() {
    assert_unreviewed_checkpoint(ReviewFailure::InputBudget);
}

#[test]
fn review_tokenizer_error_retains_exact_unreviewed_native_checkpoint_without_publication() {
    assert_unreviewed_checkpoint(ReviewFailure::Tokenizer);
}

fn assert_unreviewed_checkpoint(failure: ReviewFailure) {
    with_isolated_data("compiler-unreviewed-native-checkpoint", |_| {
        crate::settings::save(&crate::settings::Settings {
            auto_ingest_enabled: true,
            ..Default::default()
        })
        .unwrap();
        let (dir, vault, origin, source) = request_fixture();
        let original = std::fs::read(dir.path().join(&source.raw_path)).unwrap();
        let plan =
            session::sources::prepare(&source, REQUEST, &origin, "en", |_, _| Ok(800)).unwrap();
        assert_eq!(plan.windows.len(), 1);
        let context = session::begin(&vault, &origin, source, RoleUsage::Foreground).unwrap();
        let human_path = human_file(dir.path(), &context);
        let before = Pending::try_load(dir.path()).unwrap();
        let reminders = serde_json::to_value(&before.pending).unwrap();
        assert!(before.compile_jobs[0].attempts[0]
            .compiler_progress
            .is_none());
        let mut calls = Vec::new();
        let mut raw_claims = None;
        let mut raw_structure = None;
        let mut review_token_checks = 0;
        let error = step(
            &vault,
            &context,
            "en",
            &AtomicBool::new(false),
            |_, user| {
                let input: Value = serde_json::from_str(user).unwrap();
                if input.get("requiredExpressionIds").is_some() {
                    review_token_checks += 1;
                    assert_eq!(
                        input["compilation"]["version"],
                        "CanonicalSessionMaterializationV1"
                    );
                    assert_eq!(input["requiredClaimIds"].as_array().unwrap().len(), 1);
                    if matches!(failure, ReviewFailure::Tokenizer) {
                        return Err("synthetic review tokenizer unavailable".into());
                    }
                    Ok(match failure {
                        ReviewFailure::Transport => 800,
                        ReviewFailure::InputBudget => 3321,
                        ReviewFailure::Tokenizer => unreachable!(),
                    })
                } else {
                    Ok(800)
                }
            },
            |_, user, _, _, stage| {
                calls.push(stage);
                match stage {
                    CompilerSchema::Claims => {
                        let output = raw_reply(stage, user);
                        let value: Value = serde_json::from_str(&output).unwrap();
                        assert_eq!(value["claims"].as_array().unwrap().len(), 1);
                        assert_eq!(
                            value["claims"][0]["action"],
                            "Please request the synthetic report."
                        );
                        raw_claims = Some(output.clone());
                        Ok(output)
                    }
                    CompilerSchema::Compilation => {
                        let output = raw_reply(stage, user);
                        assert_eq!(
                            serde_json::from_str::<Value>(&output).unwrap()["version"],
                            "SessionStructureV1"
                        );
                        raw_structure = Some(output.clone());
                        Ok(output)
                    }
                    CompilerSchema::Review => {
                        assert!(matches!(failure, ReviewFailure::Transport));
                        Err(REVIEW_UNAVAILABLE.into())
                    }
                }
            },
        )
        .err()
        .expect("unavailable review cannot return a successful reviewed result");
        assert_eq!(review_token_checks, 1);
        let expected_calls = match failure {
            ReviewFailure::Transport => vec![
                CompilerSchema::Claims,
                CompilerSchema::Compilation,
                CompilerSchema::Review,
            ],
            ReviewFailure::InputBudget | ReviewFailure::Tokenizer => {
                vec![CompilerSchema::Claims, CompilerSchema::Compilation]
            }
        };
        assert_eq!(calls, expected_calls);
        match failure {
            ReviewFailure::Transport => assert!(error.message.contains(REVIEW_UNAVAILABLE)),
            ReviewFailure::InputBudget => assert!(error.message.contains("cannot fit")),
            ReviewFailure::Tokenizer => {
                assert!(error
                    .message
                    .contains("synthetic review tokenizer unavailable"))
            }
        }
        let pending = Pending::try_load(dir.path()).unwrap();
        let job = &pending.compile_jobs[0];
        let attempt = &job.attempts[0];
        assert_eq!(job.state, WorkState::Partial);
        assert_eq!(attempt.state, WorkState::Partial);
        assert_eq!(error.outcome.as_ref().unwrap().state, WorkState::Partial);
        assert!(error.finalization_error.is_none());
        assert_eq!(job.reason.as_deref(), Some("semantic_review_unavailable"));
        assert_eq!(
            attempt.reason.as_deref(),
            Some("semantic_review_unavailable")
        );
        assert_eq!(attempt.checks.original_source, CheckState::Passed);
        assert_eq!(attempt.checks.source_schema, CheckState::Passed);
        assert_eq!(attempt.checks.semantic_review, CheckState::Unavailable);
        assert_eq!(attempt.checks.eligible_units, 1);
        assert_eq!(attempt.checks.processed_units, 0);
        assert_eq!(attempt.checks.omitted_units, 1);
        assert!(!attempt.checks.completed_compilation());
        let progress = serde_json::to_value(&attempt.compiler_progress).unwrap();
        assert!(
            progress.is_object(),
            "a newly generated unreviewed draft must be durable"
        );
        assert_eq!(progress["sourceRevision"], context.source.source_revision);
        assert_eq!(progress["compileSignature"], context.compile_signature);
        assert_eq!(progress["planRevision"], plan.revision);
        assert_eq!(progress["language"], "en");
        assert_eq!(progress["nextPacket"], 0);
        assert_eq!(progress["batches"], json!([]));
        // JSON lookup deliberately compiles before any future Rust field exists.
        assert_eq!(
            progress["unreviewedBatch"],
            json!({
                "index":0,
                "packetRevision":plan.packet_revision(0).unwrap(),
                "extractionOutput":raw_claims.unwrap(),
                "compilationOutput":raw_structure.unwrap(),
                "reviewOutput":null
            })
        );
        assert!(attempt.outputs.is_empty());
        assert!(attempt.prepared_outputs.is_empty());
        assert!(job.receipts.is_empty());
        assert!(pending.receipts.is_empty());
        assert_eq!(serde_json::to_value(&pending.pending).unwrap(), reminders);
        assert_eq!(
            std::fs::read(dir.path().join(&context.source.raw_path)).unwrap(),
            original
        );
        assert_eq!(std::fs::read(&human_path).unwrap(), HUMAN);
        for path in [&context.index_path, &context.log_path, &context.report_path] {
            assert!(!dir.path().join(path).exists());
        }
        let queue_before = std::fs::read(Pending::path(dir.path())).unwrap();
        assert!(session::complete(
            &vault,
            &context,
            std::slice::from_ref(&context.summary_path)
        )
        .is_err());
        assert_eq!(
            std::fs::read(Pending::path(dir.path())).unwrap(),
            queue_before
        );
        assert_eq!(std::fs::read(&human_path).unwrap(), HUMAN);
        if matches!(failure, ReviewFailure::Transport) {
            let automatic = session::begin(
                &vault,
                &origin,
                context.source.clone(),
                RoleUsage::Automatic,
            )
            .expect_err("an unchanged unavailable review requires explicit retry");
            assert!(
                automatic.contains("SEMANTIC_ADAPTER_REQUIRED"),
                "{automatic}"
            );
            assert_eq!(
                std::fs::read(Pending::path(dir.path())).unwrap(),
                queue_before
            );
            let retry = session::begin(
                &vault,
                &origin,
                context.source.clone(),
                RoleUsage::Foreground,
            )
            .unwrap();
            assert_ne!(retry.attempt_id, context.attempt_id);
            assert_ne!(
                retry.role_snapshot.snapshot_id,
                context.role_snapshot.snapshot_id
            );
            let retry_pending = Pending::try_load(dir.path()).unwrap();
            let retry_attempt = retry_pending.compile_jobs[0].attempts.last().unwrap();
            assert_eq!(
                serde_json::to_value(&retry_attempt.compiler_progress).unwrap(),
                progress
            );
            assert!(retry_attempt.outputs.is_empty());
            assert!(retry_attempt.prepared_outputs.is_empty());
            assert!(!retry_attempt.checks.completed_compilation());
            assert!(retry_pending.compile_jobs[0].receipts.is_empty());
            let mut retry_calls = Vec::new();
            let publication_error = step(
                &vault,
                &retry,
                "en",
                &AtomicBool::new(false),
                |_, user| {
                    let payload: Value = serde_json::from_str(user).unwrap();
                    if payload.get("requiredExpressionIds").is_some() {
                        assert!(!dir.path().join(&retry.index_path).exists());
                        assert_eq!(std::fs::read(&human_path).unwrap(), HUMAN);
                    }
                    Ok(800)
                },
                |_, user, _, _, stage| {
                    retry_calls.push(stage);
                    assert_eq!(stage, CompilerSchema::Review);
                    session::compiler::fixture_model(stage, user, false)
                },
            )
            .err()
            .expect("fresh review cannot acquire an unrelated human file");
            assert_eq!(retry_calls, vec![CompilerSchema::Review]);
            assert!(publication_error
                .message
                .contains("existing summary ownership or original lineage is unresolved"));
            assert_eq!(
                publication_error.outcome.as_ref().unwrap().state,
                WorkState::Failed
            );
            assert!(publication_error.finalization_error.is_none());
            let reviewed_pending = Pending::try_load(dir.path()).unwrap();
            let previous = &reviewed_pending.compile_jobs[0].attempts[0];
            let fresh = reviewed_pending.compile_jobs[0].attempts.last().unwrap();
            assert_eq!(previous.state, WorkState::Partial);
            assert_eq!(fresh.state, WorkState::Failed);
            assert!(!fresh.checks.completed_compilation());
            assert!(fresh.outputs.is_empty());
            assert!(fresh.prepared_outputs.is_empty());
            let finished = serde_json::to_value(&fresh.compiler_progress).unwrap();
            assert!(finished.get("unreviewedBatch").is_none());
            assert_eq!(finished["nextPacket"], 1);
            assert!(finished["batches"][0]["reviewOutput"].is_string());
            assert_eq!(
                finished["batches"][0]["extractionOutput"],
                progress["unreviewedBatch"]["extractionOutput"]
            );
            assert_eq!(
                finished["batches"][0]["compilationOutput"],
                progress["unreviewedBatch"]["compilationOutput"]
            );
            assert!(reviewed_pending.compile_jobs[0].receipts.is_empty());
            assert!(reviewed_pending.receipts.is_empty());
            assert_eq!(
                std::fs::read(dir.path().join(&context.source.raw_path)).unwrap(),
                original
            );
            assert_eq!(std::fs::read(&human_path).unwrap(), HUMAN);
            for path in [&retry.index_path, &retry.log_path, &retry.report_path] {
                assert!(!dir.path().join(path).exists());
            }
        }
    });
}

