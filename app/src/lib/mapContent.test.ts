import { describe, expect, it } from "vitest";
import { renderMapDraft } from "./mapContent";
import { sha256 } from "./tidyRun";
import fixture from "./mapContent.fixture.json";

const evidence = [{ path: "wiki/synthetic.md", link: "[[wiki/synthetic.md]]", revision: "a".repeat(64),
  excerpt: "Synthetic source.", sourceChars: 17, truncated: false }];

describe("new map generated-section boundaries", () => {
  it("matches the same draft bytes accepted by the native publication validator", async () => {
    expect(await renderMapDraft(fixture.cluster, fixture.body, fixture.evidence, fixture.created))
      .toBe(fixture.content);
  });
  it("records the exact generated bytes separately from editable title and annotations", async () => {
    const body = "Synthetic relationship [[wiki/synthetic.md]].\n";
    const result = await renderMapDraft("Synthetic topic", body, evidence, "2026-11-10");
    expect(result).toContain(`map_generated: ${JSON.stringify({ version: 1, bodyRevision: await sha256(body) })}`);
    expect(result).toContain(`<!-- myco:map-generated:v1 -->\n${body}<!-- /myco:map-generated -->\n`);
    expect(result.indexOf('title: "Map: Synthetic topic"')).toBeLessThan(result.indexOf("<!-- myco:map-generated"));
    expect(result).toContain('"path":"wiki/synthetic.md"');
    expect(await renderMapDraft("Synthetic topic", body, evidence, "2026-11-10")).toBe(result);
  });

  it.each(["", "  \n", "<!-- myco:map-generated:v1 -->injected", "<!-- /myco:map-generated -->", "<!-- MYCO:map-generated:v2 -->", "Synthetic\0text"])("rejects ambiguous generated content %j", async body => {
    await expect(renderMapDraft("Synthetic", body, evidence, "2026-11-10"))
      .rejects.toMatchObject({ status: "pending", code: "validation_rejected" });
  });
});
